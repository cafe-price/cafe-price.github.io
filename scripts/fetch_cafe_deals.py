# 같은 상품 페이지의 다른 옵션(예: 12개입 상품에 24개입 옵션 가격)이 온 경우, 그 가격을
# 기존 상품의 관측 이력에 넣으면 평균가·할인 배지가 왜곡된다. 병합에서 걸러낸 id를 모아
# 가격 이력 기록에서 제외한다.
SKIPPED_OPTION_IDS: set[str] = set()


def name_signature(name: str) -> tuple:
    """상품명 비교용 서명 — 쉼표로 나뉜 규격 토큰을 정렬해 묶습니다.

    2026-11-19 11시 회차: `성진 인절미 콩가루` 가 같은 페이지에서 `2kg, 1개`(기존)와
    `1개, 2kg`(새 pageKey) 로 토큰 순서만 바뀌어 와 중복으로 실렸습니다. 토큰 집합이 같으면
    같은 규격으로 보고 중복으로 처리합니다.
    """
    return tuple(sorted(p.strip() for p in str(name or "").split(",") if p.strip()))


def merge_deals(previous: list[dict], fresh: list[dict]) -> list[dict]:
    """productId 기준 중복 제거 병합. 새 수집 결과가 같은 상품이면 최신 값으로 갱신한다.

    로켓배송이 아니거나 단가(`unitPrice`)가 계산되지 않은 상품은 여기서 걸러진다.
    """
    merged: dict[str, dict] = {}
    order: list[str] = []
    SKIPPED_OPTION_IDS.clear()
    # 같은 상품이 **다른 판매 페이지(productId)** 로 중복 검색되는 경우가 있습니다.
    # 2026-11-18 13시 회차: `두유 190ml 24개` 조회에서 `약콩두유 오리지널 190ml×24`(23,250원)가
    # pageKey 293207724 · 1555608082 두 페이지로 함께 와서 같은 상품이 두 번 실렸습니다.
    # 상품명과 가격이 모두 같으면 같은 상품으로 보고 먼저 들어온 것만 남깁니다(가격 이력도 남기지 않음).
    seen_name_price: dict[tuple[str, object], str] = {}
    seen_name_sig: dict[tuple[tuple, object], str] = {}
    for d in previous:
        if is_excluded(d.get("productName", "")) or not passes_listing_filter(d):
            continue
        with_vendor_item_id(d)
        while d.get("category") in CATEGORY_ALIASES:
            d["category"] = CATEGORY_ALIASES[d["category"]]
        d["category"] = override_category(d.get("productName", ""), d.get("category", ""))
        pid = str(d.get("productId") or "")
        if not pid:
            continue
        key = (d.get("productName", ""), d.get("productPrice"))
        sig = (name_signature(d.get("productName", "")), d.get("productPrice"))
        if key in seen_name_price or sig in seen_name_sig:
            print(f"[skip] 같은 상품의 중복 판매 페이지(productId {pid}) — 기존 상품 유지: "
                  f"{(d.get('productName') or '')[:48]}")
            SKIPPED_OPTION_IDS.add(pid)
            continue
        seen_name_price[key] = pid
        seen_name_sig.setdefault(sig, pid)
        if pid not in merged:
            order.append(pid)
        merged[pid] = d
    for d in fresh:
        pid = str(d.get("productId") or "")
        if not pid or is_excluded(d.get("productName", "")) or not passes_listing_filter(d):
            continue
        with_vendor_item_id(d)
        if pid in merged and is_other_option(merged[pid], d):
            print(f"[skip] 같은 상품 페이지(productId {pid})의 다른 옵션 — 기존 상품 유지: "
                  f"{(d.get('productName') or '')[:48]}")
            SKIPPED_OPTION_IDS.add(pid)   # 이 가격은 다른 옵션 가격이므로 이력에 남기지 않는다
            continue
        # 이미 있는 상품은 **기존 카테고리를 유지**합니다. 새 조회의 카테고리로 덮으면 키워드가 이웃
        # 카테고리 상품을 잡아올 때마다 소속이 흔들립니다(돔뚜껑이 빨대·홀더로 · 코코넛밀크가 크림·연유로
        # 덮였던 사례). 상품명 오버라이드가 있으면 그 값이 우선합니다.
        forced = forced_category(d.get("productName", ""))
        prev_cat = merged[pid].get("category") if pid in merged else None
        d["category"] = forced or prev_cat or d.get("category", "")
        key = (d.get("productName", ""), d.get("productPrice"))
        sig = (name_signature(d.get("productName", "")), d.get("productPrice"))
        if pid not in merged and (key in seen_name_price or sig in seen_name_sig):
            print(f"[skip] 같은 상품의 중복 판매 페이지(productId {pid}) — 다른 페이지 "
                  f"{seen_name_price.get(key) or seen_name_sig.get(sig)} 유지: "
                  f"{(d.get('productName') or '')[:48]}")
            SKIPPED_OPTION_IDS.add(pid)
            continue
        seen_name_price.setdefault(key, pid)
        seen_name_sig.setdefault(sig, pid)
        if pid not in merged:
            order.append(pid)
        merged[pid] = d
    deals = [merged[pid] for pid in order]
    relabeled = relabel_units(deals)
    if relabeled:
        print(f"[relabel] 1개입 벌크 포장 {relabeled}건을 개당 → 용량 단가로 표기 변경")
    return deals


def relabel_units(deals: list[dict]) -> int:
    """기존 상품의 단가 표기를 상품명 기준으로 다시 계산한다(벌크 단일 포장·옵션 나열 보정용).

    현재 기준(`unitBasis`)을 그대로 힌트로 쓰므로 비교 축이 흔들리지 않고, 같은 기준으로
    계산한 값이 달라졌을 때만(벌크 1개입 → 용량 단가, 옵션 나열 개수 보정 등) 저장합니다.
    """
    changed = 0
    for d in deals:
        if d.get("unitPrice") is None:
            continue
        basis = d.get("unitBasis")
        bases = BASIS_BASES.get(basis)
        if not bases:
            continue
        unit, new_basis, pack = calc_unit_price(d.get("productName", ""),
                                                d.get("productPrice") or 0,
                                                bases, d.get("category"))
        if not unit:
            continue
        if round(unit) != d.get("unitPrice") or new_basis != basis or pack != d.get("packNote"):
            d["unitPrice"] = round(unit)
            d["unitBasis"] = new_basis
            d["packNote"] = pack
            changed += 1
    return changed


def sort_deals(deals: list[dict]) -> list[dict]:
    rank = {c: i for i, c in enumerate(CATEGORIES)}
    return sorted(
        deals,
        key=lambda d: (rank.get(d.get("category", ""), 99),
                       d.get("unitPrice") if d.get("unitPrice") else 10 ** 12),
    )


def write_json(payload: dict) -> None:
    tmp = OUT_PATH.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    tmp.replace(OUT_PATH)


def main(argv: list[str]) -> int:
    global VERBOSE_CANDIDATES
    VERBOSE_CANDIDATES = "--show-candidates" in argv
    dry_run = "--dry-run" in argv
    replace = "--replace" in argv
    now = datetime.now(timezone.utc)
    targets = select_targets(argv)
    try:
        max_requests = int(_opt(argv, "--max-requests") or DEFAULT_MAX_REQUESTS)
    except ValueError:
        max_requests = DEFAULT_MAX_REQUESTS
    try:
        assume_used = int(_opt(argv, "--assume-used") or 0)
    except ValueError:
        assume_used = 0

    # --batch/--only/--wave 로 범위를 직접 지정하지 않았고 상한이 키워드 수보다 적으면 순환 갱신
    explicit_scope = any(a in ("--batch", "--only", "--wave")
                         or a.startswith(("--batch=", "--only=", "--wave=")) for a in argv)
    if not explicit_scope:
        rotated = rotate_targets(targets, max_requests, now)
        if rotated is not targets:
            print("[info] 순환 갱신: " + " · ".join(f"{t['category']}/{t['query']}" for t in rotated))
        targets = rotated

    print(f"[info] now={kst_str(now)}  unlock_at={UNLOCK_AT.astimezone(KST).strftime('%Y-%m-%d %H:%M KST')}")

    access_key = os.environ.get("COUPANG_ACCESS_KEY", "").strip()
    secret_key = os.environ.get("COUPANG_SECRET_KEY", "").strip()
    sub_id = os.environ.get("COUPANG_SUB_ID", "").strip()

    recent = hour_window(load_usage(), now)
    print(f"[info] 최근 1시간 기록된 호출 {len(recent)}회 (상한 {HOURLY_CAP}회) · 이번 실행 상한 {max_requests}회 · 가산 {assume_used}회")

    if dry_run:
        print("[dry-run] 수집 계획:")
        for i, t in enumerate(targets, 1):
            print(f"  {i}. [{t['category']}] {t['query']} (기준: {' → '.join(t['bases'])}, 최대 {LIMIT}개)")
        print(f"[dry-run] 요청 {len(targets)}회(이번 실행 상한 {max_requests}) · 간격 {SAFE_INTERVAL_SEC}초 · "
              f"병합={'아니오(교체)' if replace else '예'} · 키 설정됨={bool(access_key and secret_key)}")
        print("[dry-run] 네트워크 요청/파일 쓰기 없음.")
        return 0

    if "--prune-only" in argv or "--recompute" in argv:
        previous = load_previous()
        prev_deals = previous.get("deals") or []
        prune = "--prune-only" in argv
        deals, discounted, restored, dropped = refresh_from_history(previous, prune)
        write_json({
            "status": "ok",
            "updatedAt": previous.get("updatedAt") or kst_str(datetime.now(timezone.utc)),
            "statsAt": kst_str(datetime.now(timezone.utc)),
            "notice": "",
            "watchlist": [],
            "categories": CATEGORIES,
            "count": len(deals),
            "priceStats": {"products": len(load_history().get("products") or {}), "discounts": discounted},
            "deals": deals,
        })
        label = "prune" if prune else "recompute"
        print(f"[{label}] 네트워크 요청 없이 갱신: {len(prev_deals)} → {len(deals)}건 · "
              f"할인 배지 {discounted}건 · 이전 deals.json 복원 {restored}건")
        print(f"       (로켓배송 + 단가 확인 필터로 {dropped}건 제외 · 제외 키워드 {len(EXCLUDE_KEYWORDS)}종 "
              f"· 가격 이력 {len(load_history().get('products') or {})}개 상품 보존)")
        return 0

    if cooldown_active(now):
        print("[skip] 쿠팡 API 쿨다운 기간입니다. 네트워크 요청 없이 종료합니다.")
        return 0

    if not (access_key and secret_key):
        print("[error] COUPANG_ACCESS_KEY / COUPANG_SECRET_KEY 가 없습니다.", file=sys.stderr)
        return 2

    # 시간당 한도 안전장치(2026-11-17 18시 회차 추가): 실행이 늦어져 60분 윈도우에 직전 회차 호출이
    # 남아 있는 상태로 8회를 더 보내면 한 시간에 10회를 넘길 수 있다. 남은 여유가 2회 미만이면
    # 아예 호출하지 않고 끝내고, 그보다 많으면 이번 실행 상한을 남은 여유까지 낮춘다.
    remaining = HOURLY_CAP - len(recent) - assume_used
    if remaining < 2:
        print(f"[skip] 최근 1시간 호출 {len(recent) + assume_used}회 — 남은 여유 {max(remaining, 0)}회(2회 미만)라 "
              "이번 회차는 API를 호출하지 않고 종료합니다.")
        return 0
    if max_requests > remaining:
        print(f"[info] 남은 여유 {remaining}회에 맞춰 이번 실행 상한을 {max_requests} → {remaining}회로 낮춥니다.")
        max_requests = remaining

    try:
        deals, failed = collect(access_key, secret_key, sub_id, targets, max_requests, assume_used)
    except urllib.error.HTTPError as exc:
        detail = ""
        try:
            detail = exc.read().decode("utf-8")[:400]
        except Exception:
            pass
        print(f"[error] HTTP {exc.code} {detail}", file=sys.stderr)
        if exc.code in (403, 429):
            print("[abort] 호출 제한 응답입니다. deals.json 을 건드리지 않고 중단합니다.", file=sys.stderr)
        return 1
    except Exception as exc:  # 네트워크/파싱 오류 — 기존 데이터 유지
        print(f"[error] {type(exc).__name__}: {exc}", file=sys.stderr)
        return 1

    if not deals:
        print("[warn] 수집된 상품이 없습니다. 기존 deals.json 을 유지합니다.")
        return 0

    previous = load_previous()
    prev_deals = previous.get("deals") or []
    merged = sort_deals(merge_deals([] if replace else prev_deals, deals))
    print(f"[filter] 수집 후보 {len(deals)}건 중 로켓배송+단가 확인 {sum(1 for d in deals if passes_listing_filter(d))}건만 반영 "
          f"(비로켓·단가 미산출 {len(deals) - sum(1 for d in deals if passes_listing_filter(d))}건 제외)")

    # 수집 결과를 가격 이력에 기록하고, 누적 평균가·할인율을 계산해 함께 저장한다.
    updated_at = kst_str(datetime.now(timezone.utc))
    hist = load_history()
    reconcile_from_previous(hist, previous)
    # 가격 이력에는 **사이트에 실리는 상품(로켓+단가 확인)만** 기록한다.
    # 검색 결과에 섞여 온 같은 productId 의 다른 옵션(비로켓 낱개 등) 가격이 이력에 섞이면
    # 평균가·최저가·할인 배지가 실제 노출 상품과 다른 가격을 기준으로 계산된다.
    recorded = sum(1 for d in deals if passes_listing_filter(d)
                   and str(d.get("productId") or "") not in SKIPPED_OPTION_IDS
                   and add_observation(hist, d, updated_at, "수집 결과"))
    finalize_history(hist)
    discounted = apply_price_stats(merged, hist)
    save_history(hist)

    write_json({
        "status": "ok",
        "updatedAt": updated_at,
        "statsAt": updated_at,
        "notice": "",
        "watchlist": [],
        "categories": CATEGORIES,
        "count": len(merged),
        "priceStats": {"products": len(hist.get("products") or {}), "discounts": discounted},
        "deals": merged,
    })
    print(f"[done] 총 {len(merged)}개 상품으로 deals.json 갱신 "
          f"(이전 {len(prev_deals)} + 신규/필터 통과 {len(deals)} · 병합 {'교체' if replace else '적용'})")
    print(f"[history] 관측 {recorded}건 기록 · 이력 상품 {len(hist.get('products') or {})}개 · "
          f"평균 대비 할인 {discounted}건")
    if failed:
        print(f"[note] 응답이 비어 있던 카테고리: {', '.join(sorted(set(failed)))}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
