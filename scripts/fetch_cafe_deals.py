VENDOR_ITEM_RE = re.compile(r"[?&]vendorItemId=(\d+)")


def vendor_item_id(deal: dict) -> str:
    """쿠팡 상품 링크에서 **vendorItemId**(옵션 단위 식별자)를 뽑는다.

    API 응답의 `productId` 는 상품 **페이지**(pageKey) 단위라, 한 페이지에서 함께 파는
    다른 옵션(예: `아이팩피앤디 92파이 16온스 아이스컵` ↔ `98파이 돔리드 컵뚜껑`)이
    같은 값을 갖는다. 그래서 같은 productId 로 들어온 다른 옵션이 기존 상품을
    조용히 덮어써 상품이 사라지고 평균가가 섞이지 않도록, 옵션이 다르면 기존 상품을
    유지하고 새 옵션은 건너뛴다(2026-11-16 22시 회차 데이터 점검에서 발견).
    """
    if isinstance(deal, dict):
        vid = str(deal.get("vendorItemId") or "").strip()
        if vid:
            return vid
        url = deal.get("productUrl") or ""
    else:
        url = str(deal or "")
    m = VENDOR_ITEM_RE.search(url)
    return m.group(1) if m else ""


def option_name_key(deal: dict) -> str:
    """옵션 비교용 상품명 정규화(공백·쉼표 제거). vendorItemId 를 못 읽을 때만 쓰는 보조 수단."""
    return re.sub(r"[\s,]+", "", str((deal or {}).get("productName") or "")).lower()


def with_vendor_item_id(deal: dict) -> dict:
    """`vendorItemId` 필드를 상품 링크에서 복원해 항상 채운 상태로 만든다(제자리 갱신).

    쿠팡 응답의 `vendorItemId` 가 비어 오는 경우가 있어(2026-11-18 점검: deals.json 394건 전부 공백)
    필드만 보고 판단하면 옵션 가드가 동작하지 않는다. 링크에 남아 있는 값으로 채워 둔다.
    """
    if isinstance(deal, dict):
        vid = vendor_item_id(deal)
        if vid:
            deal["vendorItemId"] = vid
    return deal


def is_other_option(stored: dict, fresh: dict) -> bool:
    """같은 productId 인데 실제 판매 옵션(vendorItemId)이 다른 상품인지.

    양쪽 모두 vendorItemId 를 읽을 수 있으면 그 값으로 판정한다. 한쪽이라도 링크에서
    읽지 못하면(드물게 vendorItemId 없는 링크) 상품명이 다를 때만 다른 옵션으로 본다.
    """
    a = vendor_item_id(stored)
    b = vendor_item_id(fresh)
    if a and b:
        return a != b
    na = option_name_key(stored)
    nb = option_name_key(fresh)
    return bool(na and nb and na != nb)


def passes_listing_filter(deal: dict) -> bool:
    """사이트에 실을 수 있는 상품인지 — **로켓배송이면서 단가가 계산된 상품만** 남긴다.

    비로켓 상품과, 상품명에 용량·수량이 없어 `unitPrice` 를 낼 수 없는 상품은
    수집·병합·재계산 어느 경로에서도 `deals.json` 에 넣지 않는다.
    (가격 이력 `data/price_history.json` 의 기존 관측은 지우지 않고 그대로 둔다.)
    """
    return deal.get("isRocket") is True and deal.get("unitPrice") is not None


